export function normalizeLocale(input: string | null | undefined): LocaleCode {
  if (!input) {
    return DEFAULT_LOCALE;
  }

  const normalized = input.trim().toLowerCase();
  if (normalized in dictionaries) {
    return normalized as LocaleCode;
  }

  return legacyLanguageMap[normalized] || DEFAULT_LOCALE;
}

export function getLocaleLabel(locale: LocaleCode) {
  return languageOptions.find((item) => item.value === locale)?.label || locale;
}
